"""Generate the simulator instruction corpus from the assembler matrix.

For every mnemonic in data/golden/asm/matrix/*.tsv this writes one program,
<outdir>/<MNEMONIC>.x68, that executes every distinct legal encoding of the
mnemonic once, each inside its own block:

           ORG     $10100+k*64        ; fixed slots: label values never
    T<k>:  MOVE    #$2700,SR          ; depend on instruction sizes
           MOVE.L  #T<k+1>,NEXT       ; where HANDLER resumes
           LEA     USTK,A0
           MOVE    A0,USP
           LEA     SSTK,SP
           MOVEM.L REGS<j>,D0-D7/A0-A6 ; one of four register sets
    B<k>:  MOVE    #<sr>,SR           ; CCR pattern, sometimes user mode
           <instruction under test>   ; branch targets BK -> B<k>, FW ->
                                      ; T<k+1>; data BK/FW -> $2E00/$2F00
           BRA     T<k+1>

All exception vectors point at HANDLER, which jumps to (NEXT), so a faulting
case resumes at the next block (run with exceptions enabled, -e). Memory at
$1000-$2FFF holds ILLEGAL words so stray jumps fault rather than run away;
the register sets point A0-A6 into a data patch at $3000.

Excluded: STOP (ends the run), TRAP #15 (I/O tasks; covered separately) and
control-flow instructions whose target is backwards (BK, *, *(PC,..)), which
would loop. #BK/#FW immediates become #$1F00 (as in the matrix). The
fixed slots also sidestep the original assembler's "Symbol value differs
between first and second pass" on some bit field forms. The programs are assembled with the reference assembler and run
in both simulators by tools/reference/compare_sim.sh; golden results come
from tools/reference/regenerate_sim_golden.sh (oracle only).

Usage: gen_sim_corpus.py <matrix-dir> <outdir>
"""

import os
import re
import sys

FLOW = {"BRA", "BSR", "BCC", "BCS", "BEQ", "BGE", "BGT", "BHI", "BHS", "BLE",
        "BLO", "BLS", "BLT", "BMI", "BNE", "BPL", "BVC", "BVS", "JMP", "JSR",
        "DBCC", "DBCS", "DBEQ", "DBF", "DBGE", "DBGT", "DBHI", "DBHS", "DBLE",
        "DBLO", "DBLS", "DBLT", "DBMI", "DBNE", "DBPL", "DBRA", "DBT", "DBVC",
        "DBVS"}

REG_SETS = [
    # D0-D7, A0-A6
    ([0, 1, 2, 3, 4, 5, 6, 7],
     [0x3000, 0x3010, 0x3020, 0x3030, 0x3040, 0x3050, 0x3060]),
    ([0x80000000, 0x7FFFFFFF, 0xFFFFFFFF, 0x00008000, 0x00007FFF, 0xFFFF0000,
      0x0000FFFF, 0x00000080],
     [0x3080, 0x3090, 0x30A0, 0x30B0, 0x30C0, 0x30D0, 0x30E0]),
    ([0x12345678, 0x9ABCDEF0, 0x0F0F0F0F, 0xF0F0F0F0, 0x00000001, 0xFFFFFFFE,
      0x55555555, 0xAAAAAAAA],
     [0x3004, 0x3018, 0x3028, 0x3034, 0x3048, 0x3058, 0x3068]),
    ([0x00000099, 0x00000045, 0x00000010, 0x00000020, 0x0000001F, 0x00000021,
      0x00000000, 0x00000040],
     [0x3000, 0x3010, 0x3020, 0x3031, 0x3041, 0x3050, 0x3060]),
]

# Data patch at $3000: ILLEGAL on every other word so jumps into it stop.
PATCH_WORDS = [0x8001, 0x7FFE, 0xFFFF, 0x0080, 0x8000, 0x0001, 0xC3C1, 0x5555,
               0xAAAA, 0x1234, 0xFF00, 0x00FF, 0x4E71, 0x9999, 0x0045, 0x7F7F]


def legal_cases(path):
    seen = set()
    cases = []
    with open(path) as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            # source, object hex, diagnostic ("-", "WARNING: ..." or "ERROR: ...")
            if len(parts) < 3 or not parts[1] or parts[2].startswith("ERROR"):
                continue
            src, enc = parts[0], parts[1]
            if enc in seen:
                continue
            seen.add(enc)
            cases.append(src)
    return cases


def excluded(src):
    fields = src.split(None, 1)
    mnem = fields[0].split(".")[0].upper()
    ops = fields[1] if len(fields) > 1 else ""
    if mnem == "STOP":
        return True
    if mnem == "TRAP" and ops.strip() in ("#15", "#$F", "#$f"):
        return True
    if mnem in FLOW and (re.search(r"\bBK\b", ops) or re.search(r"\*(?!\+)", ops)):
        return True
    return False


def slot(k):
    return 0x10100 + k * 64


def program(mnemonic, cases):
    out = []
    out.append(f"* Simulator corpus: every legal {mnemonic} encoding from the")
    out.append("* assembler matrix, one block each. Generated by")
    out.append("* tools/reference/gen_sim_corpus.py; do not edit.")
    out.append("NEXT     EQU     $F00000")
    out.append("USTK     EQU     $7000")
    out.append("SSTK     EQU     $8000")
    out.append("RL       REG     D2-D4/A3")
    out.append("         ORG     0")
    out.append("         DC.L    SSTK,START")
    out.append("         DCB.L   62,HANDLER")
    out.append("         ORG     $1000")
    out.append("         DCB.W   $1000,$4AFC")
    out.append("         ORG     $3000")
    words = []
    for i in range(128):
        words.append(0x4AFC if i % 2 == 0 else PATCH_WORDS[(i // 2) % len(PATCH_WORDS)])
    for i in range(0, len(words), 8):
        out.append("         DC.W    " + ",".join(f"${w:04X}" for w in words[i:i + 8]))
    out.append("         ORG     $10000")
    out.append("HANDLER  MOVEA.L NEXT,A0")
    out.append("         JMP     (A0)")
    out.append("START    BRA     T0")
    for k, src in enumerate(cases):
        j = k % len(REG_SETS)
        ccr = (k * 7) % 32
        sr = (0x0000 if k % 5 == 4 else 0x2700) | ccr
        test = re.sub(r"#(BK|FW)\b", "#$1F00", src)
        if mnemonic in FLOW:
            test = re.sub(r"\bBK\b", f"B{k}", test)
            test = re.sub(r"\bFW\b", f"T{k + 1}", test)
        else:
            # Data operands: absolute addresses in the ILLEGAL area, so
            # writes never modify code; BK(PC) reads the block itself.
            test = re.sub(r"\bBK\(PC\)", f"B{k}(PC)", test)
            test = re.sub(r"\bBK\b", "$2E00", test)
            test = re.sub(r"\bFW\b", "$2F00", test)
        out.append(f"         ORG     ${slot(k):X}")
        out.append(f"T{k}       MOVE    #$2700,SR")
        out.append(f"         MOVE.L  #T{k + 1},NEXT")
        out.append("         LEA     USTK,A0")
        out.append("         MOVE    A0,USP")
        out.append("         LEA     SSTK,SP")
        out.append(f"         MOVEM.L REGS{j},D0-D7/A0-A6")
        out.append(f"B{k}       MOVE    #${sr:04X},SR")
        out.append(f"         {test}")
        out.append(f"         BRA     T{k + 1}")
    out.append(f"         ORG     ${slot(len(cases)):X}")
    out.append(f"T{len(cases)}       MOVE    #$2700,SR")
    out.append("         SIMHALT")
    for j, (d, a) in enumerate(REG_SETS):
        vals = d + a
        out.append(f"REGS{j}    DC.L    " + ",".join(f"${v:08X}" for v in vals[:8]))
        out.append("         DC.L    " + ",".join(f"${v:08X}" for v in vals[8:]))
    out.append("         END     START")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    matrix_dir, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    total = 0
    for name in sorted(os.listdir(matrix_dir)):
        if not name.endswith(".tsv"):
            continue
        mnemonic = name[:-4]
        cases = [c for c in legal_cases(os.path.join(matrix_dir, name)) if not excluded(c)]
        if not cases:
            continue
        total += len(cases)
        with open(os.path.join(outdir, mnemonic + ".x68"), "w") as f:
            f.write(program(mnemonic, cases))
        if mnemonic.startswith("BF"):
            with open(os.path.join(outdir, mnemonic + ".flags"), "w") as f:
                f.write("-b\n")
    print(f"{total} cases")


if __name__ == "__main__":
    main()
